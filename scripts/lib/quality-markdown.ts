/** Renders the quality report as docs/DATA_QUALITY_REPORT.md (deterministic, no wall-clock time). */
import type { QualityReport } from './quality.ts';

const esc = (s: string) => s.replace(/\|/g, '\\|');

function list(items: readonly string[], max = 40): string {
  if (items.length === 0) return '_None._\n';
  const shown = items.slice(0, max).map((s) => `- ${s}`);
  if (items.length > max)
    shown.push(`- … and ${items.length - max} more (see \`public/data/quality-report.json\`)`);
  return `${shown.join('\n')}\n`;
}

export function qualityMarkdown(r: QualityReport, datasetVersion: string): string {
  const t = r.totals;
  const g = r.graph;
  const lines: string[] = [];
  lines.push(
    '# Data quality report',
    '',
    '<!-- Generated by scripts/build-data.ts — do not edit by hand. -->',
    '',
    `Dataset \`${datasetVersion}\`, built from the OpenStreetMap snapshot retrieved ${r.builtFrom}.`,
    '',
    '## Totals',
    '',
    '| Measure | Count |',
    '|---|---|',
    `| Campus places (places.json) | ${t.places} |`,
    `| Off-campus context places (context-places.json, opt-in layer) | ${t.contextPlaces} |`,
    `| Campus inventory buildings (buildings.geojson) | ${t.buildings} |`,
    `| Unnamed inventory buildings | ${r.unnamedBuildings.total} |`,
    `| Footprints held for boundary review / excluded as outside | ${r.membership.uncertain.length} / ${r.membership.outside.length} |`,
    `| Unverified detected footprints (detections.geojson) | ${t.detections} |`,
    `| Relations | ${t.relations} |`,
    `| Graph nodes / edges / components | ${g.nodes} / ${g.edges} / ${g.components} |`,
    `| Graph edges on campus / outside (kept as public context) | ${g.campusEdges} / ${g.offCampusEdges} |`,
    '',
    'Building coverage, membership rules and every excluded footprint: [CAMPUS_BUILDING_COVERAGE.md](CAMPUS_BUILDING_COVERAGE.md).',
    '',
    '## Important categories',
    '',
    'A category is _sparse_ with fewer than 3 campus records. Empty categories are shown as honest empty states in the app.',
    'Off-campus places never count towards a campus category; they are listed separately for the opt-in context layer.',
    '',
    '| Category | Campus | Nearby outside (context layer) | Status |',
    '|---|---|---|---|',
    ...r.importantCategories.map(
      (c) => `| ${esc(c.label)} | ${c.onCampus} | ${c.nearbyOutside} | ${c.status} |`,
    ),
    '',
    '## Building heights',
    '',
    'Only `osm-height` is a sourced measurement; `osm-levels-estimate` multiplies `building:levels` by a configured',
    'storey height and `fallback` is a placeholder render height.',
    '',
    '| Height source (inventory) | Buildings |',
    '|---|---|',
    ...Object.entries(r.heightSources).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '| Fidelity level (0 outline, 1 levels estimate, 2 tagged height, 3 surveyed) | Buildings |',
    '|---|---|',
    ...Object.entries(r.fidelityLevels).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## Building flags (reported, never "fixed")',
    '',
    list(r.buildingFlags.map((f) => `\`${f.id}\` ${f.code}: ${f.message}`)),
    '## OSM tagging needed',
    '',
    list(r.osmTaggingNeeded.map((f) => `\`${f.id}\` ${f.name ?? '(unnamed)'}: ${f.reason}`)),
    '## Duplicate and overlapping footprints',
    '',
    list([
      ...r.duplicatesResolved.map(
        (d) => `Duplicate: kept \`${d.kept}\`, removed \`${d.dropped}\` (IoU ${d.iou}).`,
      ),
      ...r.overlaps.map(
        (o) =>
          `${o.kind}: \`${o.a}\` / \`${o.b}\` overlap ${o.intersectionM2} m² (IoU ${o.iou}, ${Math.round(o.smallerCovered * 100)}% of the smaller).`,
      ),
    ]),
    '## Routing graph',
    '',
    `- Largest component holds ${(g.largestComponentShare * 100).toFixed(1)}% of nodes; ${g.footEdges} of ${g.edges} edges are walkable.`,
    `- Component sizes (largest first): ${g.componentSizes.join(', ') || 'none'}${g.components > g.componentSizes.length ? ', …' : ''}`,
    `- Routable ways: ${g.stats.routableWays}; duplicate overlapping segments dropped: ${g.stats.duplicateEdgesDropped};` +
      ` zero-length segments merged: ${g.stats.zeroLengthSegmentsMerged}; segments outside map bounds: ${g.stats.segmentsOutsideBounds};` +
      ` contradictory oneway tags: ${g.stats.directionConflicts}.`,
    '- No synthetic connections are ever added between components.',
    '- Every edge carries `campus` (midpoint inside the boundary). Off-campus edges are real, legal public paths kept for context.',
    '',
    `### Edges crossing the campus boundary (${g.boundaryCrossingEdges.length})`,
    '',
    'The only graph links between campus and town. Whether they are open gates is not recorded.',
    '',
    list(
      g.boundaryCrossingEdges.map(
        (e) => `edge ${e.edgeId} (way/${e.osmWayId}, ${e.highway}), inside node ${e.insideNode.join(', ')}`,
      ),
    ),
    `### Edges through building interiors (${g.edgesThroughBuildings.length})`,
    '',
    'More than 0.5 m of the edge inside a footprint. Kept as mapped (they may be passages, covered driveways or underpasses);',
    'edges with no grade-separation tag on either the way or the building are flagged for OSM review.',
    '',
    list(
      g.edgesThroughBuildings.map(
        (e) =>
          `edge ${e.edgeId} way/${e.osmWayId} (${e.highway}) through \`${e.buildingId}\`: ${e.insideM} m inside; ` +
          (e.needsOsmReview ? '**no grade-separation tags: OSM review**' : e.evidenceTags.join(', ')),
      ),
      60,
    ),
    `## Places not connected to the walking graph (${r.placesNotConnectedToGraph.length})`,
    '',
    'No foot-accessible graph node within the configured connector distance; these places are searchable but not routable.',
    '',
    list(r.placesNotConnectedToGraph.map((p) => `\`${p.id}\` ${p.displayName} (${p.campusZone})`)),
    `## Places without a location (${r.placesWithoutLocation.length})`,
    '',
    list(r.placesWithoutLocation.map((p) => `\`${p.id}\` ${p.displayName}`)),
    '## Entrances',
    '',
    `${r.entrances.total} mapped entrance nodes; ${r.entrances.attached} attached to a building outline.`,
    '',
    list(r.entrances.unattached.map((id) => `Unattached: \`${id}\``)),
    '## Duplicates',
    '',
    list([
      ...r.duplicates.ids.map((id) => `Duplicate id \`${id}\``),
      ...r.duplicates.locations.map(
        (d) => `Same location ${d.location.join(', ')}: ${d.ids.map((i) => `\`${i}\``).join(', ')}`,
      ),
    ]),
    '## Verification',
    '',
    `Records by status: ${Object.entries(r.verification.byStatus)
      .map(([k, v]) => `${k} ${v}`)
      .join(', ')}.`,
    `${r.verification.withoutLastVerifiedAt} places have no recorded verification date (OSM imports are never marked verified).`,
    '',
    `## Largest unnamed campus buildings (survey priorities)`,
    '',
    list(r.unnamedBuildings.largestOnCampus.map((b) => `\`${b.id}\` ${b.displayName}, ${b.areaM2} m²`)),
    '## Skipped features',
    '',
    list(r.skippedFeatures.map((s) => `\`${s.ref}\`: ${s.reason}`)),
    '## Map keys',
    '',
    `Lock version ${r.directory.lockVersion ?? 'none'}: ${r.directory.keyed} keyed of ${r.directory.eligible} eligible campus buildings in ${r.directory.cells} grid cells.`,
    '',
    list([
      ...r.directory.unkeyed.map((id) => `Unkeyed (run \`npm run data:keys\`): \`${id}\``),
      ...r.directory.unkeyable.map((id) => `Outside the key grid: \`${id}\``),
      ...r.directory.staleLockKeys.map((id) => `Lock key for an id no longer in the inventory: \`${id}\``),
    ]),
    '## Detections and context',
    '',
    `Microsoft footprints shipped ${r.detections.microsoft.shipped} (of ${r.detections.microsoft.candidates} ≥ 50 % inside; ` +
      `${r.detections.microsoft.matched} matched OSM and are not shown). Google-only points shipped ${r.detections.google.shipped}. ` +
      `Off-campus basemap land use dropped: ${r.basemap.droppedOffCampusAreas.length}.`,
    '',
    '## Curated data',
    '',
    `Files present: ${r.curated.filesPresent.join(', ') || 'none'}. Aliases ${r.curated.aliases}, overrides ${r.curated.overrides}, ` +
      `organizations ${r.curated.organizations} (${r.curated.anchoredOrganizations} anchored to a mapped place).`,
    '',
    '## Notes',
    '',
    list(r.notes),
  );
  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}
